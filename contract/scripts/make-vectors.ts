// Writes vectors.json: known keys, codes and expected results that every implementation
// (doctor-web, Android) must reproduce. Re-run only when the format changes.
import { writeFileSync } from 'node:fs';
import { b64u, encodeCheckIn, generateEncryptionKey } from '../contract.ts';
import { makeFixture } from './fixtures.ts';
import { keyToJson } from './lib.ts';

const iat = 1_795_000_000; // fixed so "now" in the vectors stays inside the validity window
const f = await makeFixture({ iat });
const other = await generateEncryptionKey();
const checkIn = { name: 'Maria Dela Cruz', age: 54, brgy: 'Brgy. Malinis', pub: b64u(f.patient.pub) };

writeFileSync(new URL('../vectors.json', import.meta.url), JSON.stringify({
  format: 1,
  note: 'Test-only keys. Generated by scripts/make-vectors.ts.',
  root_pub: b64u(f.root.pub),
  patient: keyToJson(f.patient),
  other_patient: keyToJson(other),
  now: iat + 60,
  record_qr: f.qr,
  expected_record: f.record,
  expected_staff_name: 'Ana Reyes',
  expected_clinic_name: 'RHU San Isidro',
  check_in: checkIn,
  check_in_text: encodeCheckIn(checkIn),
  base45: [['AB', 'BB8'], ['Hello!!', '%69 VD92EX0'], ['base-45', 'UJCLQE7W581']],
}, null, 2) + '\n');
console.log('wrote vectors.json');
